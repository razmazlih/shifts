import { test, expect, request as requestFactory } from "@playwright/test";
import { mkdir } from "node:fs/promises";
import type { Template, WeekData } from "../../src/lib/types";

const WEEK = "2039-02-06";
const entry = { title: "סיור ערב מתבנית", group: "PATROL", startTime: "15:00", endTime: "23:00", required: 1, days: [0, 2] };

test("template edits, cloning and per-user favorites persist; stale writes reject and existing weeks remain unchanged", async ({ context, baseURL }) => {
  const origin = baseURL ?? "http://localhost:3000";
  const payload = (data: unknown) => ({ data, headers: { Origin: origin } });
  const admin = context.request;
  const login = await admin.post("/api/auth/login", payload({ email: "admin@demo.local", password: process.env.DEMO_ADMIN_PASSWORD ?? "DemoAdmin!2026" }));
  expect(login.ok()).toBeTruthy();
  const created = await admin.post("/api/templates", payload({ name: "תבנית מקור לניהול", weekStart: WEEK, entries: [entry] }));
  expect(created.status()).toBe(201);
  let { template } = await created.json() as { template: Template };
  const initial = await (await admin.get(`/api/weeks?week=${WEEK}`)).json() as WeekData;
  const applied = await admin.post("/api/templates/apply", payload({ weekStart: WEEK, revision: initial.revision, templateId: template.id, scope: { days: [0, 2], groups: ["PATROL"] } }));
  expect(applied.status(), await applied.text()).toBe(200);
  const baseline = await applied.json() as WeekData;
  const wrongTeam = await admin.post("/api/templates/apply", payload({ weekStart: WEEK, revision: baseline.revision, templateId: template.id, scope: { days: [0, 2], groups: ["MANAGERS"] } }));
  expect(wrongTeam.status()).toBe(400);
  expect((await (await admin.get(`/api/weeks?week=${WEEK}`)).json()).shifts).toEqual(baseline.shifts);
  const renamed = await admin.patch("/api/templates", payload({ templateId: template.id, revision: template.revision, name: "שם חדש שנשמר" }));
  expect(renamed.status()).toBe(200);
  template = (await renamed.json()).template;
  expect(template.revision).toBe(1);
  const staleApplication = await admin.post("/api/templates/apply", payload({ weekStart: WEEK, revision: baseline.revision, templateId: template.id, templateRevision: 0, scope: { days: [0, 2], groups: ["PATROL"] } }));
  expect(staleApplication.status()).toBe(409);
  expect((await admin.patch("/api/templates", payload({ templateId: template.id, revision: 0, name: "דריסה ישנה" }))).status()).toBe(409);
  expect((await admin.delete("/api/templates", payload({ templateId: template.id, revision: 0 }))).status()).toBe(409);
  const cloned = await admin.post("/api/templates", payload({ cloneTemplateId: template.id, revision: template.revision }));
  expect(cloned.status()).toBe(201);
  const clone = (await cloned.json()).template as Template;
  expect(clone.id).not.toBe(template.id);
  expect(clone.shifts).toEqual(template.shifts);
  const edited = await admin.patch("/api/templates", payload({ templateId: template.id, revision: template.revision, name: template.name, entries: [{ ...entry, endTime: "22:00" }] }));
  expect(edited.status()).toBe(200);
  template = (await edited.json()).template;
  const favorite = await admin.patch("/api/templates", payload({ templateId: template.id, favorite: true }));
  expect(favorite.status()).toBe(200);
  expect((await favorite.json()).template).toMatchObject({ favorite: true, revision: 2 });
  const all = (await (await admin.get("/api/templates")).json()).templates as Template[];
  expect(all.find(item => item.id === template.id)?.favorite).toBe(true);
  expect(all.find(item => item.id === clone.id)?.shifts).toEqual(clone.shifts);
  const current = await (await admin.get(`/api/weeks?week=${WEEK}`)).json() as WeekData;
  expect(current.shifts).toEqual(baseline.shifts);
  expect(current.revision).toBe(baseline.revision);
  expect(current.publishedRevision).toBe(baseline.publishedRevision);
  const concurrent = await Promise.all(["עריכה ראשונה", "עריכה שנייה"].map(name => admin.patch("/api/templates", payload({ templateId: template.id, revision: 2, name }))));
  expect(concurrent.map(response => response.status()).sort()).toEqual([200, 409]);
  const worker = await requestFactory.newContext({ baseURL: origin });
  try {
    expect((await worker.post("/api/auth/login", payload({ email: "employee@demo.local", password: process.env.DEMO_EMPLOYEE_PASSWORD ?? "DemoWorker!2026" }))).status()).toBe(200);
    expect((await worker.get("/api/templates")).status()).toBe(403);
    expect((await worker.patch("/api/templates", payload({ templateId: template.id, favorite: false }))).status()).toBe(403);
    expect((await worker.post("/api/templates", payload({ cloneTemplateId: template.id, revision: 3 }))).status()).toBe(403);
  } finally { await worker.dispose(); }
  expect((await admin.delete("/api/templates", payload({ templateId: template.id, revision: 3 }))).status()).toBe(200);
  expect((await admin.delete("/api/templates", payload({ templateId: clone.id, revision: clone.revision }))).status()).toBe(200);
});

test("manager edits a template then opens explicit day and team preparation without changing the week", async ({ page, context, baseURL }) => {
  const origin = baseURL ?? "http://localhost:3000";
  const payload = (data: unknown) => ({ data, headers: { Origin: origin } });
  await context.request.post("/api/auth/login", payload({ email: "admin@demo.local", password: process.env.DEMO_ADMIN_PASSWORD ?? "DemoAdmin!2026" }));
  const created = await context.request.post("/api/templates", payload({ name: "תבנית ממשק לעריכה", weekStart: WEEK, entries: [entry] }));
  expect(created.status()).toBe(201);
  const template = (await created.json()).template as Template;
  const baseline = await (await context.request.get(`/api/weeks?week=${WEEK}`)).json() as WeekData;
  await page.goto("/");
  await page.getByLabel("בחירת שבוע", { exact: true }).fill(WEEK);
  await expect(page.locator(".calendar-loading")).toBeHidden();
  await page.locator(".schedule-actions > summary").click();
  await page.getByRole("button", { name: "תבניות שבוע", exact: true }).click();
  const modal = page.getByRole("dialog", { name: "תבניות שבוע", exact: true });
  const row = modal.locator(".template-row").filter({ hasText: "תבנית ממשק לעריכה" });
  await row.locator(".template-management-actions summary").click();
  await row.getByRole("button", { name: "עריכה", exact: true }).click();
  await expect(modal.getByLabel("שם לתבנית", { exact: true })).toHaveValue("תבנית ממשק לעריכה");
  await modal.getByLabel("שם לתבנית", { exact: true }).fill("תבנית ערוכה בממשק");
  await modal.locator(".template-builder-entry").first().getByLabel("סיום", { exact: true }).fill("22:00");
  await page.setViewportSize({ width: 390, height: 844 });
  await mkdir("output/playwright/stage-b", { recursive: true });
  await modal.screenshot({ path: "output/playwright/stage-b/template-edit-mobile.png" });
  await modal.getByRole("button", { name: "שמירת השינויים בתבנית", exact: true }).click();
  const smart = page.getByRole("dialog", { name: "שיבוץ חכם", exact: true });
  await expect(smart).toBeVisible();
  await expect(smart.getByLabel("תבנית לשבוע", { exact: true })).toHaveValue(template.id);
  await smart.getByText("אפשרויות נוספות", { exact: true }).click();
  await expect(smart.getByText("ימים לשינוי", { exact: true })).toBeVisible();
  await expect(smart.getByText("צוותים לשינוי", { exact: true })).toBeVisible();
  const current = await (await context.request.get(`/api/weeks?week=${WEEK}`)).json() as WeekData;
  expect(current.shifts).toEqual(baseline.shifts);
  expect(current.revision).toBe(baseline.revision);
  await smart.getByRole("button", { name: "ביטול", exact: true }).click();
  expect((await context.request.delete("/api/templates", payload({ templateId: template.id, revision: 1 }))).status()).toBe(200);
});
